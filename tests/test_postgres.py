"""Real PostgreSQL tests using fresh local databases. Never resets existing data."""
import json
import os
from pathlib import Path
import secrets
import sys
import unittest

import psycopg
from psycopg import sql
from psycopg.conninfo import conninfo_to_dict, make_conninfo

sys.path.insert(0, str(Path(__file__).parent))
from rehearse_event import run

ADMIN_URL = os.getenv('PG_ADMIN_TEST_URL', '')


@unittest.skipUnless(ADMIN_URL, 'Set PG_ADMIN_TEST_URL for a local PostgreSQL role with CREATEDB.')
class PostgresTests(unittest.TestCase):
    def setUp(self):
        options = conninfo_to_dict(ADMIN_URL)
        if options.get('host') not in ('127.0.0.1', 'localhost', '::1'):
            self.fail('Database creation tests are restricted to a local PostgreSQL server.')
        self.database = 'aarohan_test_' + secrets.token_hex(8)
        with psycopg.connect(ADMIN_URL, autocommit=True, connect_timeout=5) as connection:
            connection.execute(sql.SQL('CREATE DATABASE {}').format(sql.Identifier(self.database)))
        self.url = make_conninfo(ADMIN_URL, dbname=self.database)

    def tearDown(self):
        # The exact name was generated by this test; no existing DB is a target.
        if not self.database.startswith('aarohan_test_'):
            raise AssertionError('Unexpected test database name.')
        with psycopg.connect(ADMIN_URL, autocommit=True, connect_timeout=5) as connection:
            connection.execute(sql.SQL('DROP DATABASE {} WITH (FORCE)').format(sql.Identifier(self.database)))

    def test_forty_teams_across_two_processes_and_restart(self):
        results = run(40, self.url)
        self.assertEqual(results['storage'], 'postgres')
        self.assertEqual(results['errors'], 0)
        print('\nPostgres HTTP rehearsal: ' + json.dumps(results))


if __name__ == '__main__':
    unittest.main(verbosity=2)
